    impl Connector for HttpConnector {
        type Stream = HttpStream<MixStream>;
        type Future =
            Pin<Box<dyn Future<Output = Result<Self::Stream, HttpClientError>> + Sync + Send>>;

        fn pool_key(&self, uri: &Uri) -> PoolKey {
            self.pool_key_for(uri)
        }

        fn connect(&self, uri: &Uri, _http_version: HttpVersion) -> Self::Future {
            // Make sure all parts of uri is accurate.
            let mut addr = uri.authority().unwrap().to_string();
            let mut auth = None;
            let mut is_proxy = false;
            let mut proxy_scheme = None;
            let mut proxy_host = None;
            let mut proxy_tls_config = None;

            if let Some(proxy) = self.config.proxies.match_proxy(uri) {
                let info = proxy.intercept.proxy_info();
                addr = proxy.via_proxy(uri).authority().unwrap().to_string();
                auth = info.basic_auth.as_ref().and_then(|v| v.to_string().ok());
                proxy_scheme = Some(info.scheme().clone());
                proxy_host = Some(info.authority().host().as_str().to_string());
                proxy_tls_config = info.tls_config().cloned();
                is_proxy = true;
            }
            #[cfg(all(target_os = "linux", feature = "ylong_base", feature = "__tls"))]
            let fchown = self.config.fchown.clone();
            let resolver = self.resolver.clone();
            let timeout = self.config.timeout.clone();
            match *uri.scheme().unwrap() {
                Scheme::HTTP => Box::pin(async move {
                    let mut time_group = TimeGroup::default();
                    time_group.set_dns_start(Instant::now());
                    let socket_addrs = dns_query(resolver, addr.as_str()).await?;
                    time_group.set_dns_end(Instant::now());
                    time_group.set_tcp_start(Instant::now());
                    #[cfg(not(all(
                        target_os = "linux",
                        feature = "ylong_base",
                        feature = "__tls"
                    )))]
                    let stream = eyeballs_connect(socket_addrs, timeout).await?;
                    #[cfg(all(target_os = "linux", feature = "ylong_base", feature = "__tls"))]
                    let stream = if let Some(fchown) = fchown {
                        eyeballs_connect_with_owner(socket_addrs, timeout, fchown.uid, fchown.gid)
                            .await?
                    } else {
                        eyeballs_connect(socket_addrs, timeout).await?
                    };

                    time_group.set_tcp_end(Instant::now());

                    let local = stream.local_addr().map_err(|e| {
                        HttpClientError::from_io_error(crate::ErrorKind::Connect, e)
                    })?;
                    let peer = stream.peer_addr().map_err(|e| {
                        HttpClientError::from_io_error(crate::ErrorKind::Connect, e)
                    })?;
                    let detail = ConnDetail {
                        protocol: ConnProtocol::Tcp,
                        local,
                        peer,
                        addr: addr.clone(),
                    };
                    let stream = if is_proxy && proxy_scheme.as_ref() == Some(&Scheme::HTTPS) {
                        let config = proxy_tls_config.unwrap_or_default();
                        let host = proxy_host.as_deref().unwrap_or(addr.as_str());
                        time_group.set_tls_start(Instant::now());
                        let stream =
                            connect_tls_with_read_ahead(config, host, stream, addr.as_str(), true)
                                .await?;
                        time_group.set_tls_end(Instant::now());
                        MixStream::ProxyHttps(stream)
                    } else {
                        MixStream::Http(stream)
                    };
                    let transport_role = if is_proxy {
                        if proxy_scheme.as_ref() == Some(&Scheme::HTTPS) {
                            TransportRole::HttpOverHttpsProxy
                        } else {
                            TransportRole::HttpOverHttpProxy
                        }
                    } else {
                        TransportRole::DirectHttp
                    };
                    let data = ConnData::builder()
                        .time_group(time_group)
                        .proxy(is_proxy)
                        .proxy_auth(auth)
                        .transport_role(transport_role)
                        .build(detail);

                    Ok(HttpStream::new(stream, data))
                }),
                Scheme::HTTPS => {
                    let host = uri.host().unwrap().to_string();
                    let port = uri.port().unwrap().as_u16().unwrap();
                    let config = self.config.tls.clone();
                    #[cfg(feature = "http3")]
                    if _http_version == HttpVersion::Http3 {
                        return Box::pin(async move {
                            let mut time_group = TimeGroup::default();
                            time_group.set_dns_start(Instant::now());
                            let addr_fut = resolver.resolve(&addr);
                            let addrs = addr_fut.await.map_err(|e| {
                                HttpClientError::from_dns_error(
                                    crate::ErrorKind::Connect,
                                    Error::new(ErrorKind::Interrupted, e),
                                )
                            })?;
                            time_group.set_dns_end(Instant::now());
                            time_group.set_quic_start(Instant::now());
                            let mut last_e = None;
                            for addr_it in addrs {
                                let udp_socket = match super::udp_stream(&addr_it).await {
                                    Ok(socket) => socket,
                                    Err(e) => {
                                        last_e = Some(e);
                                        continue;
                                    }
                                };
                                let local = udp_socket.local_addr().map_err(|e| {
                                    HttpClientError::from_io_error(crate::ErrorKind::Connect, e)
                                })?;
                                let peer = udp_socket.peer_addr().map_err(|e| {
                                    HttpClientError::from_io_error(crate::ErrorKind::Connect, e)
                                })?;
                                let detail = ConnDetail {
                                    protocol: ConnProtocol::Quic,
                                    local,
                                    peer,
                                    addr: addr.clone(),
                                };

                                let mut data = ConnData::builder()
                                    .time_group(time_group.clone())
                                    .proxy(is_proxy)
                                    .transport_role(TransportRole::DirectHttps)
                                    .build(detail);

                                let mut stream =
                                    HttpStream::new(MixStream::Udp(udp_socket), data.clone());
                                let Ok(quic_conn) =
                                    QuicConn::connect(&mut stream, &config, &host).await
                                else {
                                    continue;
                                };
                                stream.set_quic_conn(quic_conn);
                                data.time_group_mut().set_quic_end(Instant::now());
                                stream.set_conn_data(data);
                                return Ok(stream);
                            }

                            Err(last_e.unwrap_or(HttpClientError::from_str(
                                crate::ErrorKind::Connect,
                                "connect failed",
                            )))
                        });
                    }
                    Box::pin(async move {
                        let mut time_group = TimeGroup::default();
                        time_group.set_dns_start(Instant::now());
                        let socket_addrs = dns_query(resolver, addr.as_str()).await?;
                        time_group.set_dns_end(Instant::now());
                        time_group.set_tcp_start(Instant::now());
                        #[cfg(not(all(
                            target_os = "linux",
                            feature = "ylong_base",
                            feature = "__tls"
                        )))]
                        let stream = eyeballs_connect(socket_addrs, timeout).await?;
                        #[cfg(all(target_os = "linux", feature = "ylong_base", feature = "__tls",))]
                        let stream = if let Some(fchown) = fchown {
                            eyeballs_connect_with_owner(
                                socket_addrs,
                                timeout,
                                fchown.uid,
                                fchown.gid,
                            )
                            .await?
                        } else {
                            eyeballs_connect(socket_addrs, timeout).await?
                        };

                        time_group.set_tcp_end(Instant::now());

                        https_connect(
                            config,
                            addr,
                            stream,
                            is_proxy,
                            proxy_scheme,
                            proxy_host,
                            proxy_tls_config,
                            (auth, host, port),
                            time_group,
                        )
                        .await
                    })
                }
            }
        }
    }

    async fn https_connect(
        config: TlsConfig,
        addr: String,
        tcp_stream: TcpStream,
        is_proxy: bool,
        proxy_scheme: Option<Scheme>,
        proxy_host: Option<String>,
        proxy_tls_config: Option<TlsConfig>,
        (auth, host, port): (Option<String>, String, u16),
        mut time_group: TimeGroup,
    ) -> Result<HttpStream<MixStream>, HttpClientError> {
        let tcp = tcp_stream;
        let local = tcp
            .local_addr()
            .map_err(|e| HttpClientError::from_io_error(crate::ErrorKind::Connect, e))?;
        let peer = tcp
            .peer_addr()
            .map_err(|e| HttpClientError::from_io_error(crate::ErrorKind::Connect, e))?;

        time_group.set_tls_start(Instant::now());
        let origin_pin_host = format!("{host}:{port}");
        let is_https_over_https_proxy = is_proxy && proxy_scheme == Some(Scheme::HTTPS);
        let stream = if is_https_over_https_proxy {
            let proxy_config = proxy_tls_config.unwrap_or_default();
            let proxy_host = proxy_host.unwrap_or_else(|| addr.clone());
            let proxy_tls = connect_tls_with_read_ahead_buffer(
                proxy_config,
                proxy_host.as_str(),
                tcp,
                addr.as_str(),
                CONNECT_PROXY_READ_AHEAD_BUFFER,
            )
            .await?;
            let tunneled = tunnel(proxy_tls, &host, port, auth)
                .await
                .map_err(|e| HttpClientError::from_io_error(crate::ErrorKind::Connect, e))?;
            let origin_tls =
                connect_tls(config, host.as_str(), tunneled, origin_pin_host.as_str()).await?;
            MixStream::HttpsOverProxy(origin_tls)
        } else {
            let tcp = if is_proxy {
                tunnel(tcp, &host, port, auth)
                    .await
                    .map_err(|e| HttpClientError::from_io_error(crate::ErrorKind::Connect, e))?
            } else {
                tcp
            };
            let origin_tls =
                connect_tls(config, host.as_str(), tcp, origin_pin_host.as_str()).await?;
            MixStream::Https(origin_tls)
        };
        let transport_role = if is_https_over_https_proxy {
            TransportRole::HttpsOverHttpsProxy
        } else if is_proxy {
            TransportRole::HttpsOverHttpProxy
        } else {
            TransportRole::DirectHttps
        };
        time_group.set_tls_end(Instant::now());

        #[cfg(feature = "http2")]
        let alpn = match &stream {
            MixStream::Https(stream) => stream.negotiated_alpn_protocol().map(Vec::from),
            MixStream::HttpsOverProxy(stream) => stream.negotiated_alpn_protocol().map(Vec::from),
            _ => None,
        };
        let detail = ConnDetail {
            protocol: ConnProtocol::Tcp,
            local,
            peer,
            addr,
        };

        #[cfg(feature = "http2")]
        let data = ConnData::builder()
            .time_group(time_group)
            .proxy(is_proxy)
            .proxy_auth(None)
            .transport_role(transport_role)
            .negotiate(NegotiateInfo::from_alpn(alpn))
            .build(detail);

        #[cfg(not(feature = "http2"))]
        let data = ConnData::builder()
            .time_group(time_group)
            .proxy(is_proxy)
            .proxy_auth(None)
            .transport_role(transport_role)
            .build(detail);

        Ok(HttpStream::new(stream, data))
    }

